    fun generate(): List<StreamRow> = PERSONAS.flatMap { generate(it) }

    private fun generate(p: Persona): List<StreamRow> {
        val rnd = Random(p.seed)
        val rows = mutableListOf<StreamRow>()
        fun add(day: LocalDate, time: LocalTime, merchant: String, category: TransactionCategory, amount: BigDecimal, label: SpendLabel, tag: String, currency: String = "INR") {
            rows += StreamRow(p.stream, "${p.stream}-${rows.size + 1}", day.atTime(time).atZone(ZONE).toInstant(), merchant, category,
                amount, currency, label, tag)
        }
        val lastDay = FIRST_DAY.plusMonths(MONTHS).minusDays(1)
        var day = FIRST_DAY
        while (!day.isAfter(lastDay)) {
            for (r in p.regulars) {
                if (rnd.nextDouble() < r.perMonth / 30.0) add(day, timeIn(rnd, r.hours), r.name, r.category, draw(rnd, r), SpendLabel.NORMAL, "regular")
            }
            p.diningOut?.let { (range, perMonth) ->
                if (rnd.nextDouble() < perMonth / 30.0) {
                    add(day, timeIn(rnd, 19..22), "Restaurant ${rows.size + 1}", F, BigDecimal(range.first + rnd.nextInt(range.last - range.first)), SpendLabel.NORMAL, "dining")
                }
            }
            day = day.plusDays(1)
        }
        for (m in 0 until MONTHS) {
            val month = FIRST_DAY.plusMonths(m)
            for (f in p.fixed) if (m % f.everyMonths == 0L) add(month.withDayOfMonth(f.day), LocalTime.of(10, 5), f.name, f.category, BigDecimal(f.amount), SpendLabel.NORMAL, "fixed")
        }
        for (o in p.oneOffs) add(FIRST_DAY.plusMonths(o.month.toLong()).withDayOfMonth(o.day), LocalTime.of(16, 40), o.name, o.category, BigDecimal(o.amount), SpendLabel.NORMAL, o.tag, o.currency)
        inject(p, rnd, rows, ::add)
        return rows.sortedWith(compareBy<StreamRow> { it.at }.thenBy { it.id })
    }

    private fun inject(
        p: Persona, rnd: Random, rows: List<StreamRow>,
        add: (LocalDate, LocalTime, String, TransactionCategory, BigDecimal, SpendLabel, String, String) -> Unit
    ) {
        p.spikes.forEachIndexed { i, (name, times) ->
            val r = p.regulars.first { it.name == name }
            add(FIRST_DAY.plusMonths(5L + i * 3).plusDays(rnd.nextInt(25).toLong()), timeIn(rnd, r.hours), r.name, r.category,
                BigDecimal(r.median * times + rnd.nextInt(r.median)), SpendLabel.SPIKE, "spike", "INR")
        }
        p.newMerchant?.let { (name, amount) ->
            add(FIRST_DAY.plusMonths(7).plusDays(rnd.nextInt(25).toLong()), timeIn(rnd, 10..23), name, S, BigDecimal(amount), SpendLabel.NEW_MERCHANT, "new_merchant", "INR")
        }
        if (p.spikes.isEmpty()) return // the quiet streams stay quiet
        val copy = rows.filter { it.label == SpendLabel.NORMAL && it.amount >= BigDecimal(300) && it.at.atZone(ZONE).toLocalDate().isAfter(FIRST_DAY.plusMonths(3)) }
            .let { it[rnd.nextInt(it.size)] }
        val copiedAt = copy.at.atZone(ZONE).plusMinutes(3L + rnd.nextInt(40))
        add(copiedAt.toLocalDate(), copiedAt.toLocalTime(), copy.merchant, copy.category, copy.amount, SpendLabel.DUPLICATE, "duplicate", "INR")
        add(FIRST_DAY.plusMonths(9).plusDays(rnd.nextInt(25).toLong()), timeIn(rnd, 9..23), "STRIPE*VERIFY", S, BigDecimal(1 + rnd.nextInt(2)), SpendLabel.CARD_TEST, "card_test", "INR")
    }

    private fun timeIn(rnd: Random, hours: IntRange): LocalTime = LocalTime.of(hours.first + rnd.nextInt(hours.last - hours.first + 1), rnd.nextInt(60))

    /** Log-normal around the median, at least ₹1; food apps and cabs carry paise. */
    private fun draw(rnd: Random, r: Regular): BigDecimal {
        val raw = r.median * exp(rnd.nextGaussian() * r.spread)
        return BigDecimal(raw).setScale(if (r.paise) 2 else 0, RoundingMode.HALF_UP).max(BigDecimal.ONE)
    }
}
