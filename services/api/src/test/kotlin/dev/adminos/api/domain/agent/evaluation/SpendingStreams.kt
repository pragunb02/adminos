/** What a row of the synthetic set is (AOS-713). Everything but [NORMAL] is an injected anomaly the detector should alert on. */
enum class SpendLabel(val code: String) {
    NORMAL("normal"),
    /** Far above this merchant's usual (e.g. ₹4,800 at a ₹450 food app). */
    SPIKE("spike"),
    /** A large first-ever spend at a merchant never seen before. */
    NEW_MERCHANT("new_merchant"),
    /** The same charge again minutes later. */
    DUPLICATE("duplicate"),
    /** ₹1/₹2 verification charges. */
    CARD_TEST("card_test");

    val injected: Boolean get() = this != NORMAL

    companion object {
        fun fromCode(code: String) = entries.firstOrNull { it.code == code } ?: throw IllegalArgumentException("Unknown label '$code'")
    }
}

/** One synthetic spend; [tag] says what kind of normal (or injection) it is, for the report. */
data class StreamRow(
    val stream: String,
    val id: String,
    val at: Instant,
    val merchant: String,
    val category: TransactionCategory,
    val amount: BigDecimal,
    val currency: String,
    val label: SpendLabel,
    val tag: String
) {
    init {
        require(stream.isNotBlank() && id.isNotBlank() && merchant.isNotBlank() && tag.isNotBlank()) { "A row names its stream, id, merchant and tag" }
        require(amount.signum() > 0) { "A spend is positive" }
        require(!merchant.contains(',') && !tag.contains(',')) { "No commas in CSV text fields" }
    }
}

/**
 * The synthetic labelled spending streams (AOS-713, D-61 style): no real data. Each stream is one
 * imagined person's year of card and UPI spends in India, in IST, with realistic normal variation
 * (festival shopping, yearly insurance, school fees, dining out, travel, a chai twice a day) and a few
 * injected anomalies. Deterministic from the seed, and committed as `anomalies/streams.csv`, so the
 * eval is reviewable and only changes when someone regenerates it on purpose.
 */
object SpendingStreams {
    const val RESOURCE = "/anomalies/streams.csv"
    private const val HEADER = "stream,id,at,merchant,category,amount,currency,label,tag"
    const val SYNTHETIC_NOTE = "# SYNTHETIC: generated by SpendingStreams.generate() from fixed seeds (AOS-713). No real people or payments."
    val ZONE: ZoneId = ZoneId.of("Asia/Kolkata")
    val FIRST_DAY: LocalDate = LocalDate.of(2025, 10, 1)
    const val MONTHS = 12L

    fun load(resource: String = RESOURCE): List<StreamRow> {
        val text = SpendingStreams::class.java.getResource(resource)?.readText() ?: throw IllegalStateException("eval set not found: $resource")
        require(text.startsWith(SYNTHETIC_NOTE)) { "$resource must say it is synthetic" }
        val lines = text.lines().filter { it.isNotBlank() && !it.startsWith("#") }
        require(lines.first() == HEADER) { "Unexpected header in $resource" }
        return lines.drop(1).map { line ->
            val c = line.split(',')
            require(c.size == 9) { "Bad row: $line" }
            StreamRow(c[0], c[1], Instant.parse(c[2]), c[3], TransactionCategory.valueOf(c[4]), BigDecimal(c[5]), c[6], SpendLabel.fromCode(c[7]), c[8])
        }
    }

    fun write(rows: List<StreamRow>, file: File) {
        file.parentFile.mkdirs()
        file.writeText((listOf(SYNTHETIC_NOTE, HEADER) + rows.map { r ->
            listOf(r.stream, r.id, r.at, r.merchant, r.category.name, r.amount.toPlainString(), r.currency, r.label.code, r.tag).joinToString(",")
        }).joinToString("\n", postfix = "\n"))
    }

